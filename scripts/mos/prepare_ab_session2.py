def excerpt(path, secs):
    y, _ = librosa.load(str(path), sr=SR, mono=True, offset=0.0, duration=secs)
    return y.astype("float32")


def encode(y, out_path):
    with tempfile.NamedTemporaryFile(suffix=".wav", delete=True) as tmp:
        sf.write(tmp.name, y, SR)
        subprocess.run(["ffmpeg", "-y", "-loglevel", "error", "-i", tmp.name,
                        "-codec:a", "libmp3lame", "-b:a", "192k", str(out_path)], check=True)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--trials", default="results/rerank_ace/ab_trials.json")
    ap.add_argument("--candidates", default="results/rerank_ace/candidates")
    ap.add_argument("--out-dir", default="results/mos/session2")
    ap.add_argument("--secs", type=float, default=12.0)
    ap.add_argument("--block-size", type=int, default=24,
                    help="comparisons per participant (~15 min); 0 = one page with all trials")
    ap.add_argument("--n-blocks", type=int, default=8)
    ap.add_argument("--seed", type=int, default=20260728)
    ap.add_argument("--force", action="store_true",
                    help="regenerate over an existing key.csv. Only safe before any "
                         "responses have been collected against it.")
    args = ap.parse_args()

    spec = json.load(open(ROOT / args.trials))
    rng = np.random.default_rng(args.seed)
    out = ROOT / args.out_dir

    # key.csv is a record of a study that has already run, not a build artefact.  It maps
    # each trial's option A/B onto C and the rival, and the 40 collected response files
    # carry only trial_id plus a 1-5 preference, so their meaning lives entirely here.  A
    # regeneration with a different --seed, or from a changed candidate pool, would
    # reassign those roles and silently invert answers that are already on disk.  Refuse
    # by default, and check before the expensive audio work rather than after it.
    key_path = out / "key.csv"
    if key_path.exists() and not args.force:
        n_resp = len(glob.glob(str(out / "responses" / "*.json")))
        print(f"refusing to overwrite {key_path}", file=sys.stderr)
        print(f"  it already exists and {n_resp} response file(s) sit beside it; "
              f"rewriting it would re-randomise which option was C's pick.", file=sys.stderr)
        print(f"  pass --force if no responses have been collected yet, or write to a "
              f"different --out-dir.", file=sys.stderr)
        return 1

    (out / "audio").mkdir(parents=True, exist_ok=True)

    # Position of C's pick is BALANCED, not left to chance: listeners carry a position
    # bias (commonly toward whichever they heard last), and if that bias correlated with
    # which arm is C's it would land straight in the headline number. Exactly half the
    # trials show C's pick first; the order is shuffled so it is still unpredictable.
    n_trials = len(spec["trials"])
    c_first = np.array([True] * (n_trials // 2) + [False] * (n_trials - n_trials // 2))
    rng.shuffle(c_first)

    rows, key, missing = [], [], []
    for n, t in enumerate(spec["trials"], 1):
        tid = f"t{n:03d}"
        srcs = {}
        ok = True
        for role, pid in (("c", t["c_pick"]), ("rival", t["rival_pick"])):
            p = ROOT / args.candidates / (pid.replace("::", "_") + ".wav")
            if not p.is_file():
                ok = False
                missing.append(str(p.relative_to(ROOT)))
            else:
                srcs[role] = excerpt(p, args.secs)
        if not ok:
            continue

        # blind: map {C's pick, rival's pick} -> {A, B} per the balanced schedule
        roles = ["c", "rival"] if c_first[n - 1] else ["rival", "c"]
        ya, yb = srcs[roles[0]], srcs[roles[1]]
        n_s = min(len(ya), len(yb))
        ya, yb = ya[:n_s], yb[:n_s]
        # match B's level to A, then scale the PAIR together so neither is louder
        ra = np.sqrt(np.mean(ya ** 2)) + EPS
        rb = np.sqrt(np.mean(yb ** 2)) + EPS
        yb = yb * (ra / rb)
        peak = max(float(np.max(np.abs(ya))), float(np.max(np.abs(yb))), EPS)
        g = min(0.1 / ra, 0.99 / peak)          # common target RMS, never clipping
        ya, yb = (ya * g).astype("float32"), (yb * g).astype("float32")

        fa, fb = f"{tid}_A.mp3", f"{tid}_B.mp3"
        encode(ya, out / "audio" / fa)
        encode(yb, out / "audio" / fb)
        rows.append({"trial_id": tid, "file_a": fa, "file_b": fb})
        key.append({"trial_id": tid, "seed": t["seed"],
                    "opt_a_role": roles[0], "opt_b_role": roles[1],
                    "c_pick": t["c_pick"], "rival_pick": t["rival_pick"],
                    "c_margin": t["c_margin"], "settles": ";".join(t["settles"])})

    with open(out / "trials.csv", "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=["trial_id", "file_a", "file_b"])
        w.writeheader()
        w.writerows(rows)
    # Carry over any columns a later analysis added to key.csv (musecp_pick, say).  They
    # are keyed by trial_id and this script knows nothing about them, so without this a
    # --force rebuild would drop them without a word.
    fields = list(key[0].keys())
    if key_path.exists():
        with open(key_path, newline="") as fh:
            prev = {r["trial_id"]: r for r in csv.DictReader(fh)}
        extra = [c for c in (next(iter(prev.values())) if prev else {}) if c not in fields]
        if extra:
            print(f"carrying over {len(extra)} added column(s) in key.csv: "
                  f"{', '.join(extra)}")
            fields += extra
            for row in key:
                for c in extra:
                    row[c] = prev.get(row["trial_id"], {}).get(c, "")
    with open(key_path, "w", newline="") as fh:
        w = csv.DictWriter(fh, fieldnames=fields)
        w.writeheader()
        w.writerows(key)

    # Blocks: 64 comparisons is ~32 min, longer than session 1 and more than the
    # amendment should declare. Deal the trials round-robin into overlapping blocks so
    # every comparison is covered the same number of times -- no trial may end up with
    # systematically fewer ratings than its neighbours.
    from collections import Counter
    blocks = {}
    if args.block_size and args.block_size < len(rows):
        # Deal each trial's repeats into DISTINCT blocks, filling emptiest blocks first.
        # The old approach concatenated shuffled copies of the trial list and sliced fixed
        # windows; because len(rows) need not divide block_size, a window could straddle a
        # copy boundary and draw the same trial twice, so one participant rated the
        # identical comparison twice in a session and the trial lost a block of coverage.
        need = args.n_blocks * args.block_size
        reps, extra = divmod(need, len(rows))
        cap = [args.block_size] * args.n_blocks
        bl = [[] for _ in range(args.n_blocks)]
        seen = [set() for _ in range(args.n_blocks)]
        order = rows[:]
        rng.shuffle(order)
        # trials getting one extra appearance, when need is not an exact multiple
        bonus = set(t["trial_id"] for t in order[:extra])
        for tr in order:
            want = reps + (1 if tr["trial_id"] in bonus else 0)
            for b in sorted(range(args.n_blocks), key=lambda i: (-cap[i], i)):
                if want == 0:
                    break
                if cap[b] > 0 and tr["trial_id"] not in seen[b]:
                    bl[b].append(tr)
                    seen[b].add(tr["trial_id"])
                    cap[b] -= 1
                    want -= 1
            if want:
                print(f"  WARNING: trial {tr['trial_id']} placed only "
                      f"{reps - want}/{reps} times")
        for b in range(args.n_blocks):
            rng.shuffle(bl[b])
            blocks[f"block{b+1}"] = bl[b]
    else:
        blocks["all"] = rows

    for name, bl in blocks.items():
        (out / f"session2_{name}.html").write_text(
            PAGE % {"trials": json.dumps(bl)}, encoding="utf-8")
    cover = Counter(t["trial_id"] for bl in blocks.values() for t in bl)
    per_trial = [cover.get(r["trial_id"], 0) for r in rows]

    print(json.dumps({
        "trials": len(rows), "secs": args.secs,
        "per_contrast": dict(Counter(c for k in key for c in k["settles"].split(";"))),
        "c_pick_shown_as_A": sum(1 for k in key if k["opt_a_role"] == "c"),
        "blocks": {n: len(b) for n, b in blocks.items()},
        "blocks_per_trial": {"min": min(per_trial), "max": max(per_trial)},
        "est_minutes_per_participant": round(args.block_size * (2 * args.secs + 6) / 60, 1)
        if args.block_size else None,
        "missing_candidates": missing[:4], "n_missing": len(missing),
        "out_dir": str(out),
    }, indent=1))
    print("\nkey.csv is researcher-only — it says which option was C's pick.")


if __name__ == "__main__":
    raise SystemExit(main())
