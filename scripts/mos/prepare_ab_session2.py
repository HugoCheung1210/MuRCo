#!/usr/bin/env python
"""Build session 2: C vs rival metrics, two players, 5-point preference. DSP env.

Consumes `select_ab_trials.py` output. For each trial, cuts a 12 s excerpt from each
of the two candidates and renders a blinded A/B comparison.

Why 0-12 s: the regenerated region is 5-8 s of the 30 s candidate, so this window
carries 5 s of lead-in, the edit itself, and 4 s of resolution. The full 30 s track
doubles session length to hear mostly untouched audio.

Fairness details that decide whether the result means anything:
  - the two options are RMS-matched TO EACH OTHER, then peak-safe scaled together.
    A loudness difference between arms would be a preference cue that has nothing to
    do with coherence, and C's pick has no reason to be the louder one.
  - option A/B assignment is randomised per trial from a fixed seed, so which arm is
    C's pick is unpredictable to the rater but reproducible for the analyst.
  - the key (which option was C's, which contrasts the trial settles) is written to a
    SEPARATE file that never reaches the participant.

Scale matches the existing rerank A/B pilot so its numbers stay comparable:
  1 = A clearly better ... 3 = about the same ... 5 = B clearly better

Usage:
  python scripts/mos/prepare_ab_session2.py
  python scripts/mos/prepare_ab_session2.py --secs 12 --out-dir results/mos/session2
Outputs: <out-dir>/audio/*.mp3, trials.csv, key.csv, session2.html
"""
import argparse
